// Pregenerates a static SVG path for the world's landmass so the app ships no
// map libraries or topology data. Run with: npm run gen:map
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { geoEquirectangular, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)
const topology = require('world-atlas/land-110m.json')

const WIDTH = 720
const HEIGHT = 360

// Equirectangular keeps longitude linear in x, which is what makes the time
// zone bands render as exact vertical stripes over the land.
const projection = geoEquirectangular()
  .scale(WIDTH / (2 * Math.PI))
  .translate([WIDTH / 2, HEIGHT / 2])

const path = geoPath(projection).digits(1)
const d = path(feature(topology, topology.objects.land))

writeFileSync(
  new URL('../src/lib/worldPath.ts', import.meta.url),
  `// Generated by scripts/gen-world-path.mjs — do not edit by hand.\n` +
    `export const WORLD_WIDTH = ${WIDTH}\n` +
    `export const WORLD_HEIGHT = ${HEIGHT}\n` +
    `export const WORLD_LAND_PATH =\n  '${d}'\n`,
)

console.log(`wrote src/lib/worldPath.ts (${d.length} chars)`)
